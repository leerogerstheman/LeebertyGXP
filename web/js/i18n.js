  let locale = localStorage.getItem('gxp.locale') || 'zh-CN';
  if (!DICT[locale]) locale = 'zh-CN';

  const listeners = new Set();

  function t(key, fallback) {
    const table = DICT[locale] || DICT['zh-CN'];
    if (table[key] !== undefined) return table[key];
    if (DICT['zh-CN'][key] !== undefined) return DICT['zh-CN'][key];
    return fallback !== undefined ? fallback : key;
  }

  /** Interpolate: tr('key', {n: 5}) replaces {n}. */
  function tr(key, vars) {
    let out = t(key);
    if (vars) {
      for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
    }
    return out;
  }

  function getLocale() { return locale; }

  function setLocale(next) {
    if (!DICT[next]) return;
    locale = next;
    localStorage.setItem('gxp.locale', next);
    document.documentElement.lang = next === 'en' ? 'en' : 'zh-CN';
    for (const fn of listeners) {
      try { fn(locale); } catch { /* a broken listener must not block switching */ }
    }
  }

  function onLocaleChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }

  /** Toggle button label: shows the language you would switch *to*. */
  function toggleLocale() { setLocale(locale === 'zh-CN' ? 'en' : 'zh-CN'); }

  /** Pick the Chinese or English field from a server object. */
  function pick(obj, base) {
    if (!obj) return '';
    if (locale === 'en') {
      const en = obj[`${base}En`] || obj[`${base}_en`];
      if (en) return en;
    }
    return obj[base] || obj[`${base}En`] || obj[`${base}_en`] || '';
  }

  /**
   * Compliance terms are shown bilingually so a worker recognises both the
   * Chinese form used in local SOPs and the English form used by auditors and
   * vendor software.
   */
  function bilingual(zh, en) {
    if (!en || zh === en) return zh || en || '';
    return locale === 'en' ? en : `${zh} / ${en}`;
  }

  document.documentElement.lang = locale === 'en' ? 'en' : 'zh-CN';

  window.I18N = { t, tr, pick, bilingual, getLocale, setLocale, toggleLocale, onLocaleChange, DICT };
